function showKlineSheet() {
  initHandleBuyNow();
  const ua = navigator.userAgent.toLowerCase();
  const isMobile = /android|iphone|ipad|ipod/i.test(ua);
  const sheet = document.getElementById("kline-app-footer");
  const openBtn = document.getElementById("kline-open-app");
  const closeBtn = document.getElementById("kline-app-close");

  if (!isMobile || !sheet) return; // 모바일만 표시

  // 이미 이벤트가 연결되어 있으면 중복 방지
  if (!openBtn.dataset.bound) {
    openBtn.addEventListener("click", (e) => {
      e.stopPropagation();
      hideSheet();
      if (typeof window.handleBuyNow === "function") {
        saveUserLog("앱 설치 팝업 - 설치");
        window.handleBuyNow(); // 기존 앱 열기 함수 호출
      }
    });
    openBtn.dataset.bound = "true";
  }
  closeBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    saveUserLog("앱 설치 팝업 - 더보기");
    sheet.style.transform = "translateY(100%)";
    setTimeout(() => {
      sheet.style.display = "none";
      document.documentElement.style.overflow = "";
      document.body.style.overflow = "";
    }, 280);
  });
  // 시트 표시
  sheet.style.display = "block";
  requestAnimationFrame(() => {
    sheet.style.transform = "translateY(0)";
  });

  // 닫기용 내부 함수
  function hideSheet() {
    sheet.style.transform = "translateY(100%)";
    setTimeout(() => {
      sheet.style.display = "none";
    }, 280);
  }
}


      function loadNonCriticalAssets() {
        const imgs = Array.from(document.querySelectorAll("img.lazy[data-src]"));
        let i = 0;
        function loadNext() {
          if (i >= imgs.length) return;
          const img = imgs[i++];
          const realSrc = img.getAttribute("data-src");
          
          if (realSrc) {
            const temp = new Image();
            temp.src = realSrc;
            temp.onload = () => {
              img.src = realSrc;
              img.classList.add("loaded");
              img.removeAttribute("data-src");
            };
          }
          setTimeout(loadNext, 150);
        }
        loadNext();
      }